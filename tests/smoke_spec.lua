local W = dofile("tests/wowstub.lua")
describe("harness", function()
    before_each(function() W.reset() end)
    it("advances timers", function()
        local hit = false
        C_Timer.After(2, function() hit = true end)
        W.advance(1)
        assert.is_false(hit)
        W.advance(1)
        assert.is_true(hit)
    end)
    it("fires unit events only for the registered unit", function()
        local f, got = CreateFrame("Frame"), 0
        f:RegisterUnitEvent("UNIT_AURA", "player")
        f:SetScript("OnEvent", function() got = got + 1 end)
        W.fire("UNIT_AURA", "party1")
        W.fire("UNIT_AURA", "player")
        assert.equal(1, got)
    end)
end)
