local W = dofile("tests/wowstub.lua")
describe("Migrate", function()
    it("prompts when PetLeash has sets and PetCall has none, and migrates", function()
        W.reset()
        PetLeash3DB = { profiles = { Default = { sets = { City = { name = "City" } } } } }
        local ns = W.load()
        W.login()
        assert.equal("PETCALL_MIGRATE_PETLEASH", W.world.popup)
        ns.Migrate:Run()
        assert.is_true(W.world.reloaded)
        assert.is_true(PetCall3DB._petleashMigrated)
        assert.is_nil(PetLeash3DB)
    end)
    it("does not prompt when PetCall already has sets", function()
        W.reset()
        PetLeash3DB = { profiles = { Default = { sets = { City = {} } } } }
        PetCall3DB = { profiles = { Default = { sets = { Mine = { name = "Mine" } } } } }
        W.load()
        W.login()
        assert.is_nil(W.world.popup)
    end)
    it("prints once after the reload", function()
        W.reset()
        PetCall3DB = { _petleashMigrated = true }
        W.load()
        W.login()
        assert.is_nil(PetCall3DB._petleashMigrated)
        assert.is_true(W.world.printed[#W.world.printed]:find("migrated") ~= nil)
    end)
end)
