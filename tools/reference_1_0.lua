-- Usage (from repo root, on main or any commit that still has 1.0.x files):
--   git worktree add ../petcall-ref v1.0.15
--   python tools/lua.py tools/reference_1_0.lua ../petcall-ref > tests/fixtures/reference_1_0.lua
local refRoot = arg[1] or error("path to a 1.0.x checkout required")
local W = dofile("tests/wowstub.lua")
local F = dofile("tests/fixtures/PetCall3DB_1_0.lua")

local function deepcopy(t)
    if type(t) ~= "table" then return t end
    local c = {} for k, v in pairs(t) do c[k] = deepcopy(v) end return c
end

local function load1x()
    W.reset()
    for id, p in pairs(F.pets) do W.world.pets[id] = p end
    for id in pairs(F.favorites) do W.world.favorites[id] = true end
    PetCall3DB = deepcopy(F.db)
    LE_PET_JOURNAL_FILTER_COLLECTED, LE_PET_JOURNAL_FILTER_NOT_COLLECTED = 1, 2
    C_PetJournal.GetNumPets = function() local n = 0 for _ in pairs(W.world.pets) do n = n + 1 end return n, n end
    C_PetJournal.GetPetInfoByIndex = function(i)
        local ids = C_PetJournal.GetOwnedPetIDs()
        local id = ids[i]
        local p = W.world.pets[id]
        return id, p.species, true, nil, nil, nil, nil, nil, nil, nil, p.creature or (1000 + p.species)
    end
    for _, k in ipairs({ "IsFilterChecked", "IsPetTypeChecked", "IsPetSourceChecked" }) do C_PetJournal[k] = function() return true end end
    for _, k in ipairs({ "SetFilterChecked", "SetAllPetTypesChecked", "SetAllPetSourcesChecked", "SetSearchFilter", "ClearSearchFilter", "SetPetTypeFilter", "SetPetSourceChecked" }) do C_PetJournal[k] = function() end end
    C_PetJournal.GetNumPetSources = function() return 10 end
    -- globals the 1.0.x code and Ace3 need beyond tests/wowstub.lua
    LibStub = nil -- fresh library registry for every world
    UnitRace = function() return "Human", "Human" end
    geterrorhandler = function() return function(e) io.stderr:write("1.0.x error: ", tostring(e), "\n") end end
    GetSpecialization = C_SpecializationInfo.GetSpecialization
    GetSpecializationInfo = C_SpecializationInfo.GetSpecializationInfo
    local libs = { "LibStub/LibStub.lua", "CallbackHandler-1.0/CallbackHandler-1.0.lua", "AceAddon-3.0/AceAddon-3.0.lua",
        "AceEvent-3.0/AceEvent-3.0.lua", "AceTimer-3.0/AceTimer-3.0.lua", "AceDB-3.0/AceDB-3.0.lua",
        "AceLocale-3.0/AceLocale-3.0.lua", "AceConsole-3.0/AceConsole-3.0.lua", "AceSerializer-3.0/AceSerializer-3.0.lua",
        "LibPetJournal-2.0/LibPetJournal-2.0.lua" }
    for _, l in ipairs(libs) do assert(loadfile(refRoot .. "/Libs/" .. l))() end
    for _, n in ipairs({ "AceConfigRegistry-3.0", "AceConfig-3.0", "AceConfigDialog-3.0", "AceGUI-3.0", "AceDBOptions-3.0", "LibDBIcon-1.0" }) do
        setmetatable(LibStub:NewLibrary(n, 1), { __index = function() return function() return setmetatable({}, { __index = function() return function() end end }) end end })
    end
    local addon = {}
    assert(loadfile(refRoot .. "/Locales/enUS.lua"))("PetCall", addon)
    for _, f in ipairs({ "PetCall.lua", "Migrate.lua", "Triggers.lua", "Filters.lua", "Ready.lua", "SwitchTimer.lua" }) do
        assert(loadfile(refRoot .. "/" .. f))("PetCall", addon)
    end
    W.fire("ADDON_LOADED", "PetCall")
    W.fire("PLAYER_LOGIN")
    W.fire("PET_JOURNAL_LIST_UPDATE")
    W.advance(1)
    return addon
end

local out = { "-- Generated by tools/reference_1_0.lua from 1.0.x. Do not edit.", "return {" }
for wi, state in ipairs(F.worlds) do
    local addon = load1x()
    for k, v in pairs(state) do W.world[k] = v end
    for _, e in ipairs({ "ZONE_CHANGED_NEW_AREA", "GROUP_ROSTER_UPDATE", "PLAYER_SPECIALIZATION_CHANGED", "PLAYER_FLAGS_CHANGED" }) do W.fire(e, "player") end
    W.advance(1)
    local cur = addon:GetCurrentSet()
    out[#out + 1] = string.format("  [%d] = { current = %q, sets = {", wi, cur and cur.name or "")
    for name, set in addon:IterateSets() do
        local active = set:IsActive()
        -- build weights directly so inactive sets are captured too
        local tbl = addon:BuildSetWeights(set.settings, {})
        local weights, total = {}, tbl.total or 0
        for i = 1, #tbl, 2 do
            local id = tbl[i + 1]
            weights[id] = (weights[id] or 0) + tbl[i]
        end
        local parts = {}
        for id, w in pairs(weights) do parts[#parts + 1] = string.format("[%q]=%.10g", id, w) end
        table.sort(parts)
        out[#out + 1] = string.format("    [%q] = { active = %s, value = %s, total = %.10g, weights = { %s } },",
            name, tostring(active), tostring(set.value), total, table.concat(parts, ", "))
    end
    out[#out + 1] = "  } },"
end
out[#out + 1] = "}"
print(table.concat(out, "\n"))
